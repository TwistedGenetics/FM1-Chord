"""FM1-Chord: the synth's wavetables (0.7), made by adding harmonics, so both the firmware and the editor play the
very same numbers.

    tools/gen_wavetables.py OUT.h        C header: FC_WT[table][frame][sample], int16
    tools/gen_wavetables.py --js OUT.js  the same for the editor (web/editor/wavetables.js)

Four tables of eight frames, 256 samples a frame; a sound sweeps through the frames with its WT position.
  VOX    sung vowels: A E I O U, by formants on a 130 Hz voice
  PWM    a pulse narrowing from 50 % to 6 %
  DIGI   a digital, PPG-like sweep: a band of harmonics climbing over a thin saw
  GLASS  sparse, bell-like upper harmonics growing brighter
Copyright (C) 2026 Jamie (TwistedGenetics)."""
import base64
import math
import struct
import sys

N, FRAMES, H = 256, 8, 60          # samples a frame, frames, harmonics (60 x 130 Hz: 7.8 kHz)


def frame(amps, phases=None):
    out = []
    for i in range(N):
        t = i / N
        v = 0.0
        for h, a in enumerate(amps, 1):
            if a:
                v += a * math.sin(2 * math.pi * h * t + (phases[h - 1] if phases else 0.0))
        out.append(v)
    pk = max(abs(x) for x in out) or 1.0
    return [int(round(x / pk * 32767)) for x in out]


def vox(f):
    vowels = [(800, 1150, 2900), (400, 1600, 2700), (270, 2300, 3000), (450, 800, 2830), (325, 700, 2530)]
    pos = f / (FRAMES - 1) * (len(vowels) - 1)
    i = min(int(pos), len(vowels) - 2)
    u = pos - i
    fm = [a + (b - a) * u for a, b in zip(vowels[i], vowels[i + 1])]
    amps = []
    for h in range(1, H + 1):
        hz = 130.0 * h
        a = sum(g / (1 + ((hz - c) / (c * 0.12)) ** 2) for c, g in zip(fm, (1.0, 0.6, 0.25)))
        amps.append(a / h ** 0.3)
    return frame(amps)


def pwm(f):
    w = 0.5 - 0.44 * f / (FRAMES - 1)
    amps = [2 / (h * math.pi) * math.sin(h * math.pi * w) for h in range(1, H + 1)]
    return frame(amps, [math.pi / 2 - h * math.pi * w for h in range(1, H + 1)])


def digi(f):
    k = 3 + f * 5
    return frame([0.25 / h + math.exp(-((h - k) / 2.2) ** 2) for h in range(1, H + 1)])


def glass(f):
    parts = [1, 3, 5, 8, 11, 15, 20, 27, 35]
    tilt = f / (FRAMES - 1)
    amps = [0.0] * H
    for j, h in enumerate(parts):
        amps[h - 1] = (1 - tilt) / (1 + j) + tilt * (0.3 + j / len(parts))
    return frame(amps)


def tables():
    return [[g(f) for f in range(FRAMES)] for g in (vox, pwm, digi, glass)]


def main():
    t = tables()
    if len(sys.argv) == 3 and sys.argv[1] == "--js":
        flat = [v for tb in t for fr in tb for v in fr]
        b64 = base64.b64encode(struct.pack(f"<{len(flat)}h", *flat)).decode()
        open(sys.argv[2], "w").write(
            "// SPDX-License-Identifier: GPL-3.0-only\n"
            "// generated by tools/gen_wavetables.py: do not edit. The synth's wavetables (as the firmware's fc_wavetables.h):\n"
            f"// {len(t)} tables x {FRAMES} frames x {N} samples, 16-bit.\n"
            f'const B64 = "{b64}";\n'
            "const bin = typeof atob === \"function\" ? atob(B64) : Buffer.from(B64, \"base64\").toString(\"binary\");\n"
            "const u8 = new Uint8Array(bin.length);\n"
            "for (let i = 0; i < bin.length; i++) u8[i] = bin.charCodeAt(i);\n"
            "export const WT = new Int16Array(u8.buffer);\n"
            f"export const WT_N = {N}, WT_FRAMES = {FRAMES}, WT_TABLES = {len(t)};\n")
        return
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    L = ["/* generated by tools/gen_wavetables.py: do not edit */", "#pragma once", "#include <stdint.h>",
         f"#define FC_WT_N {N}u", f"#define FC_WT_FRAMES {FRAMES}u", f"#define FC_WT_TABLES {len(t)}u",
         "static const int16_t FC_WT[FC_WT_TABLES][FC_WT_FRAMES][FC_WT_N] = {"]
    for tb in t:
        L.append("    {")
        for fr in tb:
            L.append("        {" + ", ".join(map(str, fr)) + "},")
        L.append("    },")
    L += ["};", ""]
    open(sys.argv[1], "w").write("\n".join(L))


if __name__ == "__main__":
    main()
