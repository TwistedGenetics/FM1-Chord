"""FM1-Chord: the big face for the chord's name on the FM-1's screen (FONT_XL), rendered with X0X's font tools
(x0x-firmware/tools/gen_font.py) from its Barlow Semi Condensed Bold (SIL OFL 1.1, in x0x-firmware/assets/fonts).
Only the characters a chord name uses are kept, to save flash.

    tools/gen_fc_font.py OUT.h [PX]          (default 50 px)

Copyright (C) 2026 Jamie (TwistedGenetics)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "x0x-firmware" / "tools"))
import gen_font  # noqa: E402

KEEP = " #*+-/0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabdgijmnorsu"


def main():
    out = Path(sys.argv[1])
    px = int(sys.argv[2]) if len(sys.argv) > 2 else 50
    h, glyphs = gen_font.render("BarlowSemiCondensed-Bold.ttf", px, 1, False, 32, 126)
    glyphs = [g if chr(32 + i) in KEEP else (0, 0, []) for i, g in enumerate(glyphs)]
    data, offs = [], []
    for adv, bw, g in glyphs:
        offs.append(len(data))
        for y in range(h):
            row = g[y * bw:(y + 1) * bw] + [0]
            for x in range(0, bw, 2):
                data.append((row[x] << 4) | row[x + 1])
    assert len(data) < 65536
    pad = gen_font.PAD
    L = [f"/* generated by tools/gen_fc_font.py: Barlow Semi Condensed Bold {px} px (SIL OFL 1.1) */", "#pragma once",
         f"static const uint8_t FONT_XL_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        L.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    L += ["};",
          f"static const uint16_t FONT_XL_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};",
          f"static const uint8_t FONT_XL_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};",
          f"static const uint8_t FONT_XL_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};",
          f"static const felucca_font_t FONT_XL = {{ {h}, {pad}, 32, 126, FONT_XL_ADV, FONT_XL_BW, FONT_XL_OFF, "
          "FONT_XL_DATA };", ""]
    out.write_text("\n".join(L))
    print(f"font XL: {px}px h {h}, {len(data)} B")


if __name__ == "__main__":
    main()
